let current=0;
let answers=Array(questions.length).fill(null);
let timeLeft=60*60;
let submitted=false;
let countdown;

const question=document.getElementById("question");
const options=document.getElementById("options");
const questionNumber=document.getElementById("questionNumber");
const questionCount=document.getElementById("questionCount");
const progress=document.getElementById("progress");
const previousBtn=document.getElementById("previousBtn");
const nextBtn=document.getElementById("nextBtn");
const submitBtn=document.getElementById("submitBtn");
const timer=document.getElementById("timer");

questions.forEach(()=>{
const dot=document.createElement("span");
progress.appendChild(dot);
});

function renderQuestion(){
const data=questions[current];
questionNumber.textContent=`QUESTION ${String(current+1).padStart(2,"0")}`;
questionCount.textContent=`Question ${current+1} of ${questions.length}`;
question.textContent=data[0];
options.innerHTML="";
data[1].forEach((option,index)=>{
const wrapper=document.createElement("div");
wrapper.className="option";
const input=document.createElement("input");
input.type="radio";
input.name="answer";
input.id=`option${index}`;
input.value=option;
input.checked=answers[current]===option;
input.addEventListener("change",()=>{
answers[current]=option;
nextBtn.disabled=false;
submitBtn.disabled=false;
});
const label=document.createElement("label");
label.htmlFor=input.id;
const letter=document.createElement("span");
letter.textContent=String.fromCharCode(65+index);
label.appendChild(letter);
label.appendChild(document.createTextNode(option));
wrapper.appendChild(input);
wrapper.appendChild(label);
options.appendChild(wrapper);
});
previousBtn.style.display=current===0?"none":"block";
nextBtn.style.display=current===questions.length-1?"none":"block";
submitBtn.style.display=current===questions.length-1?"block":"none";
nextBtn.disabled=answers[current]===null;
submitBtn.disabled=answers[current]===null;
[...progress.children].forEach((dot,index)=>dot.classList.toggle("active",index<=current));
}

function moveNext(){
if(answers[current]===null)return;
if(current<questions.length-1){
current++;
renderQuestion();
}
}

function movePrevious(){
if(current>0){
current--;
renderQuestion();
}
}

function submitTest(){
if(submitted)return;
submitted=true;
clearInterval(countdown);
let score=0;
questions.forEach((item,index)=>{
if(answers[index]===item[2])score++;
});
localStorage.setItem("aptitudeScore",score);
localStorage.setItem("aptitudeTotal",questions.length);
localStorage.setItem("aptitudeCompleted","true");
window.location.href="/technical-round";
}

function updateTimer(){
const minutes=Math.floor(timeLeft/60);
const seconds=timeLeft%60;
timer.textContent=`${String(minutes).padStart(2,"0")}:${String(seconds).padStart(2,"0")}`;
if(timeLeft<=0){
submitTest();
return;
}
timeLeft--;
}

previousBtn.addEventListener("click",movePrevious);
nextBtn.addEventListener("click",moveNext);
submitBtn.addEventListener("click",submitTest);

renderQuestion();
updateTimer();
countdown=setInterval(updateTimer,1000);